#!/usr/bin/env python3
"""
scripts/train_baseline_models.py
--------------------------------
Trains baseline machine learning model artifacts for Smart Retail AI
using deterministic datasets generated by scripts/generate_datasets.py:

1. Product Classifier: HOG Features + RBF-kernel SVM (240 training samples)
2. Sentiment Classifier: TF-IDF + Logistic Regression (283 training samples)
3. Face Verification: Face Database with normalized embeddings (person_01)
"""

from __future__ import annotations

import csv
import pickle
from pathlib import Path

import cv2
import joblib
import numpy as np
from sklearn.feature_extraction.text import TfidfVectorizer
from sklearn.linear_model import LogisticRegression
from sklearn.pipeline import Pipeline
from sklearn.svm import SVC

from app.services.face_service import _detect_largest_face, _embedding
from app.utils.image_features import hog_descriptor

ROOT = Path(__file__).resolve().parents[1]
DATA_DIR = ROOT / "data"
MODELS_DIR = ROOT / "models"
TRAIN_DIR = DATA_DIR / "training"


def train_sentiment_model() -> Path:
    print("[1/3] Training Sentiment Analysis Model...")
    train_csv = TRAIN_DIR / "sentiment_train.csv"
    if not train_csv.exists():
        from scripts.generate_datasets import generate_sentiment_datasets
        generate_sentiment_datasets()

    texts, labels = [], []
    with open(train_csv, "r", encoding="utf-8") as f:
        reader = csv.DictReader(f)
        for row in reader:
            texts.append(row["text"])
            labels.append(row["sentiment"])

    print(f"  Training on {len(texts)} balanced customer reviews...")
    pipeline = Pipeline([
        ("tfidf", TfidfVectorizer(ngram_range=(1, 2), min_df=1)),
        ("clf", LogisticRegression(C=1.0, max_iter=300, random_state=42)),
    ])
    pipeline.fit(texts, labels)

    MODELS_DIR.mkdir(parents=True, exist_ok=True)
    out_path = MODELS_DIR / "sentiment_classifier.joblib"
    joblib.dump(pipeline, out_path)
    print(f"  Saved sentiment model to {out_path}")
    return out_path


def train_product_model() -> Path:
    print("[2/3] Training Product Classification Model...")
    product_train_dir = TRAIN_DIR / "product"
    if not product_train_dir.exists():
        from scripts.generate_datasets import generate_product_datasets
        generate_product_datasets()

    classes = ["bottle", "mug", "headphones", "shoe"]
    X, y = [], []

    for cls in classes:
        cls_dir = product_train_dir / cls
        files = sorted(cls_dir.glob("*.png"))
        print(f"  Extracting HOG features for {len(files)} {cls} samples...")
        for img_path in files:
            img = cv2.imread(str(img_path))
            if img is None:
                continue
            feat = hog_descriptor(img)
            X.append(feat)
            y.append(cls)

    X = np.array(X)
    y = np.array(y)
    print(f"  Total training feature matrix shape: {X.shape}")

    svm = SVC(kernel="rbf", C=5.0, probability=True, random_state=42)
    svm.fit(X, y)

    bundle = {
        "pipeline": svm,
        "classes": classes,
        "train_samples": len(y),
    }

    MODELS_DIR.mkdir(parents=True, exist_ok=True)
    out_path = MODELS_DIR / "product_classifier.joblib"
    joblib.dump(bundle, out_path)
    print(f"  Saved product classification model to {out_path}")
    return out_path


def build_face_db() -> Path:
    print("[3/3] Building Face Verification Database...")
    face_train_dir = TRAIN_DIR / "face"
    ref_img_path = face_train_dir / "person_01_reference.png"
    if not ref_img_path.exists():
        from scripts.generate_datasets import generate_face_datasets
        generate_face_datasets()

    ref_img = cv2.imread(str(ref_img_path))
    gray = cv2.cvtColor(ref_img, cv2.COLOR_BGR2GRAY)
    box = _detect_largest_face(gray)
    if box is None:
        # Fallback to center region if Haar missed
        h, w = gray.shape[:2]
        x, y, bw, bh = int(w * 0.1), int(h * 0.1), int(w * 0.8), int(h * 0.8)
    else:
        x, y, bw, bh = box

    face_crop = gray[y:y + bh, x:x + bw]
    embedding_data = _embedding(face_crop)

    db = {
        "person_01": embedding_data,
        "threshold": 0.50,
        "reference_bbox": [int(x), int(y), int(bw), int(bh)],
    }

    MODELS_DIR.mkdir(parents=True, exist_ok=True)
    out_path = MODELS_DIR / "face_db.pkl"
    with open(out_path, "wb") as f:
        pickle.dump(db, f)

    print(f"  Saved face database to {out_path} with reference bbox {db['reference_bbox']}")
    return out_path


def main():
    print("=" * 60)
    print("Smart Retail AI — Baseline Model Training Pipeline")
    print("=" * 60)
    train_sentiment_model()
    train_product_model()
    build_face_db()
    print("=" * 60)
    print("All ML models trained and saved to models/ successfully!")
    print("=" * 60)


if __name__ == "__main__":
    main()
